-- Backfill the child tables by following the existing uuid links to the games table.
update public.gameworlds as gameworld_row
set game_id_int = game_row.game_id_int
from public."games-metadata" as game_row
where game_row.game_id = gameworld_row.game_id;

update public.edgegap_deployments as deployment_row
set game_id_int = game_row.game_id_int
from public."games-metadata" as game_row
where game_row.game_id = deployment_row.game_id;

do $$
begin
    if exists (select 1 from public.gameworlds where game_id_int is null) then
        raise exception 'Found gameworld rows without a matching games-metadata row during game_id backfill.';
    end if;

    if exists (select 1 from public.edgegap_deployments where game_id_int is null) then
        raise exception 'Found edgegap deployment rows without a matching games-metadata row during game_id backfill.';
    end if;
end;
$$;


alter table public.profiles
add column public_id bigint generated by default as identity (sequence name public.profiles_public_id_seq start with 1 increment by 1 minvalue 1 cache 1);

with ordered_profiles as (
    select profile_row.id, nextval('public.profiles_public_id_seq') as public_id
    from public.profiles as profile_row
    where profile_row.public_id is null
    order by profile_row.created_at nulls first, profile_row.id
)
update public.profiles as profile_row
set public_id = ordered_profiles.public_id
from ordered_profiles
where ordered_profiles.id = profile_row.id;

alter table public.profiles
alter column public_id set not null;

alter table public.profiles
add constraint profiles_public_id_key unique (public_id);

-- Add the new bigint game ids before swapping out the old uuid columns.
alter table public."games-metadata"
add column game_id_int bigint generated by default as identity (sequence name public.games_metadata_game_id_seq start with 1 increment by 1 minvalue 1 cache 1);

with ordered_games as (
    select game_row.game_id, nextval('public.games_metadata_game_id_seq') as game_id_int
    from public."games-metadata" as game_row
    where game_row.game_id_int is null
    order by game_row.created_at nulls first, game_row.game_id
)
update public."games-metadata" as game_row
set game_id_int = ordered_games.game_id_int
from ordered_games
where ordered_games.game_id = game_row.game_id;


create type public.catalog_type as enum ('Mesh', 'Texture', 'Sound', 'Object');

create table public.game_object_catalog (
    catalog_id bigint generated by default as identity not null,
    version_num bigint not null,
    name text not null check (length(btrim(name)) > 0),
    description text not null,
    created_at timestamptz not null default now(),
    uploaded_by uuid not null references public.user_profiles(id),
    catalog_type public.catalog_type not null,
    data_json jsonb not null,
    primary key (catalog_id, version_num),
    constraint game_object_catalog_data_type_check check (
        jsonb_typeof(data_json) = 'object'
        and data_json ? catalog_type::text
        and data_json - catalog_type::text = '{}'::jsonb
    )
);

-- Each publication appends a revision. Only the original publisher can append to an entry.
create function public.set_catalog_version()
returns trigger language plpgsql set search_path = '' as $$
declare original public.game_object_catalog;
begin
    perform pg_advisory_xact_lock(hashtextextended('game_object_catalog:' || new.catalog_id::text, 0));
    select * into original from public.game_object_catalog where catalog_id = new.catalog_id order by version_num limit 1;
    if found and (original.uploaded_by <> new.uploaded_by or original.catalog_type <> new.catalog_type) then
        raise exception 'Catalog publisher and type cannot change';
    end if;
    select coalesce(max(version_num), 0) + 1 into new.version_num
    from public.game_object_catalog where catalog_id = new.catalog_id;
    return new;
end;
$$;
create trigger game_object_catalog_set_version before insert on public.game_object_catalog
for each row execute function public.set_catalog_version();

alter table public.game_object_catalog enable row level security;
revoke all on public.game_object_catalog from anon, authenticated;
grant select on public.game_object_catalog to anon, authenticated;
grant all on public.game_object_catalog to service_role;
grant usage, select on sequence public.game_object_catalog_catalog_id_seq to service_role;
create policy "Catalog is public" on public.game_object_catalog for select to anon, authenticated using (true);
create policy "Service role only" on public.game_object_catalog for all to service_role using (true) with check (true);
create index game_object_catalog_uploaded_by_idx on public.game_object_catalog(uploaded_by);

-- Filter after choosing the latest revision, so old names and types do not leak into search results.
create function public.search_game_object_catalog(input_query text, input_catalog_type public.catalog_type, input_offset integer, input_limit integer)
returns table(catalog_id bigint, version_num bigint, name text, description text, created_at timestamptz, catalog_type public.catalog_type)
language sql stable security invoker set search_path = '' as $$
    select latest.catalog_id, latest.version_num, latest.name, latest.description, latest.created_at, latest.catalog_type
    from (
        select distinct on (entry.catalog_id) entry.* from public.game_object_catalog entry
        order by entry.catalog_id, entry.version_num desc
    ) latest
    where (input_catalog_type is null or latest.catalog_type = input_catalog_type)
      and (strpos(lower(latest.name), lower(input_query)) > 0 or strpos(lower(latest.description), lower(input_query)) > 0)
    order by latest.created_at desc, latest.catalog_id desc
    offset greatest(input_offset, 0) limit least(greatest(input_limit, 0), 100);
$$;
revoke all on function public.search_game_object_catalog(text, public.catalog_type, integer, integer) from public;
grant execute on function public.search_game_object_catalog(text, public.catalog_type, integer, integer) to anon, authenticated, service_role;

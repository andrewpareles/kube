-- Editable model sources have their own identity, ownership, and private storage bucket.
create table public.blender_metadata (
    blender_id bigint generated by default as identity primary key check (blender_id > 0),
    uploaded_by uuid not null references public.user_profiles(id),
    created_at timestamptz not null default now()
);
alter table public.blender_metadata enable row level security;
revoke all on public.blender_metadata from anon, authenticated;
grant all on public.blender_metadata to service_role;
grant usage, select on sequence public.blender_metadata_blender_id_seq to service_role;
create policy "Service role only" on public.blender_metadata for all to service_role using (true) with check (true);

insert into storage.buckets (id, name, public)
values ('blender', 'blender', false)
on conflict (id) do update
set name = excluded.name,
    public = excluded.public;

-- Existing model revisions have no explicit Blender source. Upgrade their payload shape in place.
update public.game_object_catalog
set data_json = jsonb_set(
    jsonb_set(data_json, '{Mesh,0,blender_id}', 'null'::jsonb),
    '{Mesh,1}', '4'::jsonb
)
where catalog_item_type = 'Mesh' and data_json #>> '{Mesh,1}' = '3';

-- Every chat message a running server accepted, kept after that server is gone. There is no
-- reference to running_servers because its row is deleted the moment the server shuts down, and the
-- log has to outlive it. The message is the censored text players were shown; what was typed before
-- the profanity filter ran is never stored anywhere.
create table public.game_chats (
    game_chat_id bigint generated by default as identity primary key,
    serverid text not null,
    time_live_server timestamp with time zone not null,
    userid text not null,
    message text not null
);
-- Reading a log means asking what was said on one server, or by one person, in a stretch of time.
create index game_chats_serverid_time_idx on public.game_chats (serverid, time_live_server);
create index game_chats_userid_time_idx on public.game_chats (userid, time_live_server);
alter table public.game_chats enable row level security;
create policy "Service role only" on public.game_chats for all to service_role using (true) with check (true);

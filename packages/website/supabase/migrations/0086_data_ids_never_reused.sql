-- Data ids come from one counter that only goes up, so a deleted row's id is never handed out again. Browsers keep a data
-- file forever, so a reused id would show them the old file.
drop trigger data_metadata_set_type_id on public.data_metadata;
drop function public.set_type_id();

alter table public.data_metadata alter column data_id add generated by default as identity;
select setval(pg_get_serial_sequence('public.data_metadata', 'data_id'), coalesce(max(data_id), 0) + 1, false) from public.data_metadata;

-- The catalog sells what people make for K coins. Each item keeps its own copy of a mesh asset's data, so a later revision of
-- that asset never changes what its buyers own.
create table public.catalog_metadata (
    catalog_item_id bigint generated by default as identity primary key,
    creator_id uuid not null references public.user_profiles(id) on delete cascade,
    name text not null constraint catalog_metadata_name_check check (length(btrim(name)) between 1 and 100),
    description text constraint catalog_metadata_description_check check (description is null or length(description) <= 1000),
    price_k_coins bigint not null constraint catalog_metadata_price_check check (price_k_coins >= 0),
    is_for_sale boolean not null default true,
    data_json jsonb not null constraint catalog_metadata_data_type_check check (jsonb_typeof(data_json) = 'object' and data_json ? 'Mesh' and data_json - 'Mesh' = '{}'::jsonb),
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now()
);
create index catalog_metadata_creator_id_idx on public.catalog_metadata (creator_id);

-- An item can't be deleted while anyone but its creator owns it.
create table public.user_owned_catalog_items (
    profile_id uuid not null references public.user_profiles(id) on delete cascade,
    catalog_item_id bigint not null references public.catalog_metadata(catalog_item_id) on delete restrict,
    price_paid_k_coins bigint not null constraint user_owned_catalog_items_price_paid_check check (price_paid_k_coins >= 0),
    purchased_at timestamp with time zone not null default now(),
    primary key (profile_id, catalog_item_id)
);
create index user_owned_catalog_items_catalog_item_id_idx on public.user_owned_catalog_items (catalog_item_id);

alter table public.catalog_metadata enable row level security;
alter table public.user_owned_catalog_items enable row level security;
create policy "Catalog items for sale are public" on public.catalog_metadata for select to anon, authenticated using (is_for_sale or creator_id = auth.uid());
create policy "Service role only" on public.catalog_metadata to service_role using (true) with check (true);
create policy "Users can read what they own" on public.user_owned_catalog_items for select to authenticated using (profile_id = auth.uid());
create policy "Service role only" on public.user_owned_catalog_items to service_role using (true) with check (true);

-- Buying moves the whole price from the buyer to the creator and records that the buyer owns the item, all or nothing. It
-- answers with the buyer's balance afterwards.
create function public.buy_catalog_item(input_buyer_id uuid, input_catalog_item_id bigint) returns bigint
language plpgsql
set search_path to ''
as $$
declare
    item public.catalog_metadata;
    buyer_balance bigint;
begin
    select * into item from public.catalog_metadata where catalog_item_id = input_catalog_item_id for share;
    if not found or not item.is_for_sale then
        raise exception 'This item is not for sale.';
    end if;

    -- Both accounts are locked in the same order every time, so two people buying from each other at once can't deadlock.
    perform 1 from public.user_profiles where id in (input_buyer_id, item.creator_id) order by id for update;

    if exists (select 1 from public.user_owned_catalog_items where profile_id = input_buyer_id and catalog_item_id = input_catalog_item_id) then
        raise exception 'You already own this item.';
    end if;

    -- A spend below zero fails change_k_coins' check constraint, which is what the website reads as not enough K coins.
    if item.price_k_coins > 0 then
        perform public.change_k_coins(input_buyer_id, -item.price_k_coins, 'catalog_purchase', null::bigint, gen_random_uuid());
        perform public.change_k_coins(item.creator_id, item.price_k_coins, 'catalog_sale', null::bigint, gen_random_uuid());
    end if;

    insert into public.user_owned_catalog_items (profile_id, catalog_item_id, price_paid_k_coins)
    values (input_buyer_id, input_catalog_item_id, item.price_k_coins);

    select k_coins into buyer_balance from public.user_profiles where id = input_buyer_id;
    return buyer_balance;
end;
$$;
revoke execute on function public.buy_catalog_item(uuid, bigint) from public, anon, authenticated;

import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import test from 'node:test'
import { createAssetTexturePreview } from '../packages/website/app/assets/[asset_id]/texture/createAssetTexturePreview.ts'
import { decodeTextureToGpuBytes, decodeTexture } from '../packages/website/lib/rendering/decodeTexture.ts'
import initializeBasis from '../packages/website/lib/rendering/basis/basis_transcoder.js'

const require = createRequire(new URL('../packages/website/package.json', import.meta.url))
const sharp: typeof import('../packages/website/node_modules/sharp/lib/index.js') = require('sharp')
// Generated by Rust's convert_rgba8_pixels_to_texture_data and UploadedDataWrapper<TextureData>.
// The 16x8 image has red, half-transparent green, blue, and transparent white quadrants.
const asset = new Uint8Array(await readFile(new URL('./fixtures/asset-texture.bin', import.meta.url)))
const basis = await initializeBasis({ wasmBinary: await readFile(new URL('../packages/website/lib/rendering/basis/basis_transcoder.wasm', import.meta.url)) })
basis.initializeBasis()
const chooseRgba = () => 'rgba8unorm'
process.chdir(fileURLToPath(new URL('../packages/website', import.meta.url)))

test('texture preview decodes the Rust upload format with its dimensions, colors, alpha, and orientation intact', async () => {
    const texture = decodeTexture(asset, basis, false, chooseRgba)
    assert.equal(texture.width, 16)
    assert.equal(texture.height, 8)
    assert.equal(texture.mips.length, 5)
    assert.equal(texture.isSrgb, true)
    const png = await createAssetTexturePreview(asset)
    const { data, info } = await sharp(png).raw().toBuffer({ resolveWithObject: true })
    assert.equal(info.width, 16)
    assert.equal(info.height, 8)
    assert.equal(info.channels, 4)
    for (const { x, y, expected } of [
        { x: 2, y: 2, expected: [255, 0, 0, 255] },
        { x: 10, y: 2, expected: [0, 255, 0, 128] },
        { x: 2, y: 6, expected: [0, 0, 255, 255] },
    ]) {
        const offset = (y * info.width + x) * 4
        // Basis compression is lossy; allow small differences in the stored colors.
        expected.forEach((channel, index) => assert.ok(Math.abs(data[offset + index] - channel) <= 10))
    }
    assert.equal(data[(6 * info.width + 10) * 4 + 3], 0)
    assert.equal((await sharp(png).metadata()).format, 'png')
})

test('texture previews reject stale, truncated, or inconsistent engine assets', async () => {
    for (const length of [0, 29, asset.byteLength - 1]) assert.throws(() => decodeTexture(asset.slice(0, length), basis, false, chooseRgba))
    const stale = asset.slice()
    new DataView(stale.buffer).setBigUint64(0, BigInt(2), true)
    assert.throws(() => decodeTexture(stale, basis, false, chooseRgba), /Unsupported/)
    const invalidLength = asset.slice()
    new DataView(invalidLength.buffer).setBigUint64(8, BigInt(asset.byteLength), true)
    assert.throws(() => decodeTexture(invalidLength, basis, false, chooseRgba), /length/)
    const invalidBoolean = asset.slice()
    invalidBoolean[invalidBoolean.length - 1] = 2
    assert.throws(() => decodeTexture(invalidBoolean, basis, false, chooseRgba), /metadata/)
    const wrongDimensions = asset.slice()
    new DataView(wrongDimensions.buffer).setUint32(asset.byteLength - 14, 32, true)
    await assert.rejects(createAssetTexturePreview(wrongDimensions), /metadata mismatch/)
    const invalidKtx = asset.slice()
    invalidKtx[16] = 0
    await assert.rejects(createAssetTexturePreview(invalidKtx), /Invalid KTX2/)
})

test('concurrent previews keep their pixels after transcoder memory is released', async () => {
    const previews = await Promise.all([createAssetTexturePreview(asset), createAssetTexturePreview(asset), createAssetTexturePreview(asset)])
    for (const preview of previews) assert.deepEqual(preview, previews[0])
})

test('render textures retain every full-resolution mip, alpha, and linear color-space metadata', async () => {
    for (const isSrgb of [true, false]) {
        const input = asset.slice()
        input[input.length - 2] = isSrgb ? 1 : 0
        const output = decodeTextureToGpuBytes(input, basis, chooseRgba)
        const header = new DataView(output.buffer, output.byteOffset, output.byteLength)
        assert.deepEqual([0, 4, 8, 12, 16].map(offset => header.getUint32(offset, true)), [16, 8, 5, isSrgb ? 1 : 0, 1])
        assert.equal(output.length, 20 + (16 * 8 + 8 * 4 + 4 * 2 + 2 + 1) * 4)
        const { data } = await sharp(await createAssetTexturePreview(input)).raw().toBuffer({ resolveWithObject: true })
        assert.deepEqual(output.subarray(20, 20 + 16 * 8 * 4), new Uint8Array(data))
    }
})

test('single-row material maps decode as 2D textures without a browser-only workaround', async () => {
    const singleRow = new Uint8Array(await readFile(new URL('./fixtures/asset-texture-single-row.bin', import.meta.url)))
    const result = decodeTextureToGpuBytes(singleRow, basis, chooseRgba)
    assert.equal(result.length, 24)
    assert.deepEqual([...result.subarray(20)], [0, 55, 229, 255])
    const invalid = singleRow.slice()
    new DataView(invalid.buffer).setUint32(40, 0, true)
    assert.throws(() => decodeTextureToGpuBytes(invalid, basis, chooseRgba), /metadata mismatch/)
})

test('compressed render textures carry one block per 4x4 pixels in every mip, including mips smaller than a block', () => {
    for (const [uploadFormat, blockByteCount] of [['bc1-rgba-unorm', 8], ['bc7-rgba-unorm', 16], ['astc-4x4-unorm', 16]] as const) {
        const choices: unknown[] = []
        const output = decodeTextureToGpuBytes(asset, basis, (...choice) => { choices.push(choice); return uploadFormat })
        assert.deepEqual(choices, [[16, 8, true, true]])
        const header = new DataView(output.buffer, output.byteOffset, output.byteLength)
        assert.deepEqual([0, 4, 8, 12, 16].map(offset => header.getUint32(offset, true)), [16, 8, 5, 1, 1])
        assert.equal(output.length, 20 + (8 + 2 + 1 + 1 + 1) * blockByteCount)
    }
    assert.throws(() => decodeTextureToGpuBytes(asset, basis, () => 'r8unorm'), /Unsupported texture upload format/)
})
